"""Общее подключение к Postgres.

Отдельный модуль ради одной вещи: psycopg2 в тексте `OperationalError` печатает
разобранный DSN — хост, IP, порт и пользователя базы. Репозиторий публичный, а
вместе с ним публичны и логи прогонов GitHub Actions; маскировка секретов GitHub
ловит только точное совпадение со значением секрета, и по частям разобранный DSN
под неё не попадает. Поэтому наружу отдаём только класс ошибки, а `from None`
обрывает цепочку — чтобы исходный текст не уехал ни в лог, ни в трейсбек, который
excepthook отправляет в контур «Сигналы».
"""
import psycopg2


def connect(dsn):
    try:
        return psycopg2.connect(dsn)
    except Exception as e:
        raise RuntimeError(f"не удалось подключиться к БД ({type(e).__name__})") from None
